import test from 'node:test';
import assert from 'node:assert/strict';
import { composeKitchenRun, applyKitchenRunComposition, MaksterEngineeringCompiler } from '../packages/engineering-engine/src/index.js';
import type { ProjectModelV1 } from '../packages/project-model/src/types.js';
import fs from 'node:fs';

const fixture = JSON.parse(fs.readFileSync(new URL('file://'+process.cwd()+'/packages/project-model/examples/golden.kitchen.001.r14.site-fit.json'),'utf8')) as ProjectModelV1;

test('Kitchen Run Composer keeps exact run width without stretching carcasses',()=>{
  const c=composeKitchenRun({runId:'run-a',widthMm:4190,requirements:[
    {libraryModuleId:'base.drawers',widthMm:600},
    {libraryModuleId:'base.sink',widthMm:1100},
    {libraryModuleId:'base.storage',widthMm:600},
    {libraryModuleId:'base.oven_hob',widthMm:600},
    {libraryModuleId:'base.storage',widthMm:690},
    {libraryModuleId:'base.drawers',widthMm:600},
  ]});
  assert.equal(c.ready,true);
  assert.equal(c.allocatedWidthMm,4190);
  assert.equal(c.unallocatedWidthMm,0);
  assert.deepEqual(c.modules.map(m=>m.libraryModuleId),['base.drawers','base.sink','base.storage','base.oven_hob','base.storage','base.drawers']);
  assert.deepEqual(c.modules.map(m=>Number(m.width.mode==='fixed'?m.width.value.value:0)/10),[600,1100,600,600,690,600]);
});

test('Kitchen Run Composer uses standard cabinets and a technical filler for site remainder',()=>{
  const c=composeKitchenRun({runId:'run-b',widthMm:2475,requirements:[{libraryModuleId:'base.dishwasher',widthMm:600}],standardWidthsMm:[300,400,450,500,600,800,900]});
  assert.equal(c.ready,true);
  assert.equal(c.allocatedWidthMm,2475);
  assert.ok(c.modules.some(m=>m.libraryModuleId==='technical.base'));
  assert.equal(c.modules.reduce((s,m)=>s+(m.width.mode==='fixed'?Number(m.width.value.value)/10:0),0),2475);
});

test('Kitchen Run Composer blocks incompatible wall/base library modules',()=>{
  const c=composeKitchenRun({runId:'run-c',widthMm:1200,type:'wall',requirements:[{libraryModuleId:'base.sink'}]});
  assert.equal(c.ready,false);
  assert.ok(c.issues.some(i=>i.code==='MODULE_TYPE_MISMATCH'&&i.severity==='blocking'));
});

test('Golden Project #1 can be regenerated by Composer and still enters the existing engineering compiler',()=>{
  const original=fixture.furniture[0]!;
  const c=composeKitchenRun({runId:'golden-001-composed',widthMm:4190,requirements:[
    {libraryModuleId:'base.drawers',widthMm:600},{libraryModuleId:'base.sink',widthMm:1100},{libraryModuleId:'base.storage',widthMm:600},
    {libraryModuleId:'base.oven_hob',widthMm:600},{libraryModuleId:'base.storage',widthMm:690},{libraryModuleId:'base.drawers',widthMm:600},
  ]});
  const project=structuredClone(fixture);
  project.furniture[0]=applyKitchenRunComposition(original,c);
  const result=new MaksterEngineeringCompiler().compile(project);
  assert.equal(result.ruleSetId,'kitchen-pro-engineering-v2.7.9');
  assert.equal(result.stats.moduleCount,6);
  assert.ok(result.parts.length>0);
  assert.ok(!result.issues.some(i=>i.code==='MODULE_WIDTH_SUM_MISMATCH'));
});
